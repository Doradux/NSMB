import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import createGuestMemory from '../dist/guest_memory.mjs';

const wasm = resolve(dirname(fileURLToPath(import.meta.url)), '../dist/guest_memory.wasm');
const mem = await createGuestMemory({ locateFile: () => wasm });
const call = (name, ...args) => mem['_' + name](...args);
const reset = () => call('nsmbw_mem_reset');
const err = () => call('nsmbw_mem_error');
const pages = () => call('nsmbw_mem_pages');
const r8 = a => call('nsmbw_mem_read8', a);
const r16 = a => call('nsmbw_mem_read16', a);
const r32 = a => call('nsmbw_mem_read32', a) >>> 0;
const w8 = (a, v) => call('nsmbw_mem_write8', a, v);
const w32 = (a, v) => call('nsmbw_mem_write32', a, v);
reset();
assert.equal(pages(), 0, 'sparse until written');
assert.equal(w32(0x80001234, 0xDEADBEEF), 1);
assert.equal(r32(0x00001234), 0xDEADBEEF, 'physical MEM1 alias');
assert.equal(r32(0xC0001234), 0xDEADBEEF, 'uncached MEM1 alias');
assert.deepEqual([0,1,2,3].map(i => r8(0x80001234+i)), [0xDE,0xAD,0xBE,0xEF], 'big endian');
assert.equal(r16(0x80001235), 0xADBE, 'unaligned read');
assert.equal(pages(), 1, 'aliases share physical allocation');
assert.equal(w32(0x80000FFF, 0x11223344), 1, 'cross-page store');
assert.equal(r32(0xC0000FFF), 0x11223344, 'cross-page mirrored read');
assert.equal(pages(), 2, 'sparse pages');
assert.equal(w32(0x90002000, 0xCAFEBABE), 1);
assert.equal(r32(0xD0002000), 0xCAFEBABE, 'MEM2 uncached alias');
assert.equal(r32(0x10002000), 0xCAFEBABE, 'MEM2 physical alias');
assert.equal(w8(0xCC000000, 0xFF), 0, 'MMIO must be handled by HLE');
assert.equal(err(), 1);
assert.equal(r32(0x40000000), 0, 'unsupported 0x4000 mirror rejected');
assert.equal(err(), 1);
assert.equal(r32(0xFFFFFFFF), 0, '32-bit wrap rejected');
assert.equal(err(), 2);
assert.equal(r32(0x817FFFFF), 0, 'MEM1 boundary');
assert.equal(err(), 1);
assert.equal(r32(0x90002000), 0xCAFEBABE);
assert.equal(err(), 0, 'success clears old errors');
reset();
assert.equal(pages(), 0);
assert.equal(r32(0x80001234), 0);
console.log('PASS: WebAssembly Wii memory backing, aliasing, endian, MMIO, boundary and reset tests');
